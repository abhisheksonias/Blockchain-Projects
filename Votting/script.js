let web3;
let contract;
let accounts;

window.addEventListener("load", async () => {
  if (window.ethereum) {
    web3 = new Web3(window.ethereum);
    contract = new web3.eth.Contract(abi, contractAddress);

    document.getElementById("connectBtn").addEventListener("click", async () => {
      accounts = await ethereum.request({ method: "eth_requestAccounts" });
      document.getElementById("walletAddress").innerText = `Connected: ${accounts[0]}`;
      loadElectionState();
      getAllCandidates();
    });
  } else {
    alert("Install MetaMask!");
  }
});

async function loadElectionState() {
  const status = await contract.methods.getElectionState().call();
  document.getElementById("electionStatus").innerText = status;
}

async function getAllCandidates() {
  const result = await contract.methods.getAllCandidates().call();
  const candidatesList = document.getElementById("candidates");
  const resultsList = document.getElementById("results");

  candidatesList.innerHTML = "";
  resultsList.innerHTML = "";

  for (let i = 0; i < result[0].length; i++) {
    candidatesList.innerHTML += `<li><strong>ID:</strong> ${result[0][i]} - ${result[1][i]}</li>`;
    resultsList.innerHTML += `<li>${result[1][i]} - Votes: ${result[2][i]}</li>`;
  }
}

async function castVote() {
  const id = document.getElementById("candidateId").value;
  await contract.methods.vote(id).send({ from: accounts[0] });
  alert("Vote casted!");
  getAllCandidates();
}

async function showWinner() {
  const winner = await contract.methods.showWinner().call();
  document.getElementById("winnerInfo").innerText = `🏆 ${winner[0]} (ID: ${winner[1]}) - ${winner[2]} votes`;
}
